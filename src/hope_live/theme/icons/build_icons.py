"""Build the inline SVG icon sprite and the Django icon-name registry.

Source icons live next to this script. Run from the repository root:

    python src/hope_live/theme/icons/build_icons.py

The generated files are committed so the app does not need Node or SVGO at
runtime. Icons use the Lucide 24x24 grid with currentColor strokes.
"""

from __future__ import annotations

import re
from pathlib import Path

ICON_DIR = Path(__file__).resolve().parent
REPO_ROOT = ICON_DIR.parents[3]
SPRITE_PATH = REPO_ROOT / "src/hope_live/templates/includes/icons_sprite.html"
NAMES_PATH = REPO_ROOT / "src/hope_live/templatetags/icon_names.py"

SYMBOL_ATTRIBUTES = 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'


def build() -> None:
    symbols: list[str] = []
    names: list[str] = []

    for path in sorted(ICON_DIR.glob("*.svg")):
        name = path.stem
        text = path.read_text()
        match = re.search(r"<svg\b([^>]*)>(.*)</svg>", text, re.DOTALL)
        if not match:
            raise ValueError(f"No SVG root found in {path}")

        root_attributes, inner = match.groups()
        view_box_match = re.search(r'viewBox="([^"]+)"', root_attributes)
        if not view_box_match:
            raise ValueError(f"No viewBox found in {path}")

        inner = re.sub(r"<!--.*?-->", "", inner, flags=re.DOTALL).strip()
        indented = "\n".join(f"        {line}" for line in inner.splitlines())
        symbols.append(
            f'    <symbol id="icon-{name}" viewBox="{view_box_match.group(1)}" {SYMBOL_ATTRIBUTES}>\n'
            f"{indented}\n"
            f"    </symbol>"
        )
        names.append(name)

    if not names:
        raise ValueError(f"No icons found in {ICON_DIR}")

    SPRITE_PATH.write_text(
        "{% comment %}Generated by src/hope_live/theme/icons/build_icons.py. Do not edit by hand.{% endcomment %}\n"
        '<svg xmlns="http://www.w3.org/2000/svg" class="hidden" aria-hidden="true">\n'
        + "\n".join(symbols)
        + "\n</svg>\n"
    )

    NAMES_PATH.write_text(
        '"""Generated by src/hope_live/theme/icons/build_icons.py. Do not edit by hand."""\n\n'
        "ICON_NAMES = frozenset(\n"
        "    {\n" + "".join(f'        "{name}",\n' for name in names) + "    }\n"
        ")\n"
    )


if __name__ == "__main__":
    build()
